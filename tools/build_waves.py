"""Builds Source/Dsp/Waves.inc from AKWF single-cycle waveforms (CC0, github.com/KristofferKarlAxelEkstrand/AKWF-FREE).
Usage: python3 tools/build_waves.py <path to AKWF-FREE/AKWF>
Each wave is resampled to 2048 points, band-limited to 256 harmonics, DC removed and normalised."""
import os, sys, wave
import numpy as np

src = sys.argv[1]
# (name in the synth, AKWF folder, how to pick: centroid quantile 0..1 or explicit file index)
PICKS = [
    ("SAW", "AKWF_bw_saw", 0.5), ("SAW SOFT", "AKWF_bw_saw", 0.1), ("SAW BRIGHT", "AKWF_bw_sawbright", 0.5),
    ("SQUARE", "AKWF_bw_squ", 0.3), ("PULSE", "AKWF_bw_squ", 0.9), ("SQUARE SOFT", "AKWF_bw_squ", 0.05),
    ("SINE", "AKWF_bw_sin", 0.0), ("TRI", "AKWF_bw_tri", 0.3), ("TRI SOFT", "AKWF_bw_tri", 0.8),
    ("SINE HARM", "AKWF_sinharm", 0.5), ("SINE HARM 2", "AKWF_sinharm", 0.9),
    ("DIST 1", "AKWF_distorted", 0.2), ("DIST 2", "AKWF_distorted", 0.55), ("DIST 3", "AKWF_distorted", 0.9),
    ("E BASS 1", "AKWF_ebass", 0.2), ("E BASS 2", "AKWF_ebass", 0.5), ("E BASS 3", "AKWF_ebass", 0.85),
    ("D BASS 1", "AKWF_dbass", 0.3), ("D BASS 2", "AKWF_dbass", 0.75),
    ("FM 1", "AKWF_fmsynth", 0.15), ("FM 2", "AKWF_fmsynth", 0.4), ("FM 3", "AKWF_fmsynth", 0.65), ("FM 4", "AKWF_fmsynth", 0.9),
    ("OVERTONE 1", "AKWF_overtone", 0.25), ("OVERTONE 2", "AKWF_overtone", 0.7),
    ("RAW 1", "AKWF_raw", 0.3), ("RAW 2", "AKWF_raw", 0.75),
    ("ORGAN 1", "AKWF_eorgan", 0.2), ("ORGAN 2", "AKWF_eorgan", 0.5), ("ORGAN 3", "AKWF_eorgan", 0.8),
    ("VOICE 1", "AKWF_hvoice", 0.2), ("VOICE 2", "AKWF_hvoice", 0.5), ("VOICE 3", "AKWF_hvoice", 0.8),
    ("LINEAR 1", "AKWF_linear", 0.3), ("LINEAR 2", "AKWF_linear", 0.8),
    ("BIT 1", "AKWF_bitreduced", 0.3), ("BIT 2", "AKWF_bitreduced", 0.8),
    ("CLAV", "AKWF_clavinet", 0.6), ("PLUCK", "AKWF_pluckalgo", 0.5), ("HAND 1", "AKWF_hdrawn", 0.4), ("HAND 2", "AKWF_hdrawn", 0.85),
    ("SYM 1", "AKWF_symetric", 0.4), ("SYM 2", "AKWF_symetric", 0.8),
]

def load(path):
    w = wave.open(path)
    x = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(float)
    return x

def centroid(x):
    X = np.abs(np.fft.rfft(x))[1:64]
    X /= X.max() + 1e-9
    return (X * np.arange(1, 64)).sum() / (X.sum() + 1e-9)

out = []
for name, folder, q in PICKS:
    files = sorted(f for f in os.listdir(os.path.join(src, folder)) if f.endswith(".wav"))
    waves = [(f, load(os.path.join(src, folder, f))) for f in files]
    waves = [(f, x) for f, x in waves if len(x) == 600]
    waves.sort(key=lambda fx: centroid(fx[1]))
    f, x = waves[min(len(waves) - 1, int(q * (len(waves) - 1) + 0.5))]
    X = np.fft.rfft(x)
    Y = np.zeros(1025, dtype=complex)
    Y[1:257] = X[1:257] * (2048 / 600)
    y = np.fft.irfft(Y, 2048)
    y /= np.abs(y).max() + 1e-12
    out.append((name, folder + "/" + f, y))

with open(os.path.join(os.path.dirname(__file__), "..", "Source", "Dsp", "Waves.inc"), "w") as fh:
    fh.write("// Generated by tools/build_waves.py from AKWF (CC0). Do not edit.\n")
    fh.write("static constexpr int kNumWaves = %d;\nstatic constexpr int kWaveLen = 2048;\n" % len(out))
    fh.write("static const char* const kWaveNames[kNumWaves] = {%s};\n" % ", ".join('"%s"' % n for n, _, _ in out))
    fh.write("static const char* const kWaveSources[kNumWaves] = {%s};\n" % ", ".join('"%s"' % s for _, s, _ in out))
    fh.write("static const float kWaveData[kNumWaves][kWaveLen] = {\n")
    for n, s, y in out:
        fh.write("{" + ",".join("%.5ff" % v for v in y) + "},\n")
    fh.write("};\n")
print(len(out), "waves")
